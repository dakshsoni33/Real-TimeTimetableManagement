  using (faculty_id = public.current_faculty_id() or public.is_admin());

create policy assignment_scoped_read on public.teaching_assignment for select to authenticated
  using (faculty_id = public.current_faculty_id() or public.is_admin());

create policy enrollment_scoped_read on public.student_course for select to authenticated
  using (student_id = public.current_student_id() or public.is_admin());

create policy session_scoped_read on public.class_session for select to authenticated
  using (
    public.is_admin()
    or faculty_id = public.current_faculty_id()
    or exists (
      select 1
      from public.student s
      where s.student_id = public.current_student_id()
        and s.section_id = class_session.section_id
        and (class_session.batch_id is null or s.batch_id = class_session.batch_id)
        and (
          class_session.group_id is null
          or exists (
            select 1
            from public.student_course sc
            where sc.student_id = s.student_id
              and sc.group_id = class_session.group_id
          )
        )
    )
    or (
      status = 'CANCELLED'
      and exists (
        select 1
        from public.teaching_assignment ta
        where ta.faculty_id = public.current_faculty_id()
          and ta.section_id = class_session.section_id
          and (
            class_session.batch_id is null
            or ta.batch_id is null
            or ta.batch_id = class_session.batch_id
          )
      )
    )
  );

create policy claim_scoped_read on public.vacant_slot_claim for select to authenticated
  using (faculty_id = public.current_faculty_id() or public.is_admin());

create policy notification_recipient_read on public.notification for select to authenticated
  using (
    student_id = public.current_student_id()
    or faculty_id = public.current_faculty_id()
    or public.is_admin()
  );

create policy notification_recipient_update on public.notification for update to authenticated
  using (
    student_id = public.current_student_id()
    or faculty_id = public.current_faculty_id()
  )
  with check (
    student_id = public.current_student_id()
    or faculty_id = public.current_faculty_id()
  );

